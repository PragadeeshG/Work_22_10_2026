create table if not exists passthrough_chain_execution(
chain_execution_id bigint not null,
passthrough_chain_configuration_id bigint null,
session_id varchar(255) null,
execution_id varchar(255) null,
chain_name varchar(255) null,
execution_mode varchar(255) null,
input_payload varchar(255) null,
original_input varchar(255) null,
passthrough_output varchar(255) null,
assigned_output varchar(255) null,
transformation_output varchar(255) null,
final_output varchar(255) null,
executed_components varchar(255) null,
parallel_branch_count bigint null,
successful_branch_count bigint null,
failed_branch_count bigint null,
execution_start_time varchar(255) null,
execution_end_time varchar(255) null,
constraint passthrough_chain_execution_pk primary key(chain_execution_id));