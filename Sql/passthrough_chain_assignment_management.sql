create table if not exists passthrough_chain_assignment_management(
assignment_management_id bigint not null,
passthrough_chain_configuration_id bigint null,
chain_execution_id bigint null,
assignment_id varchar(255) null,
assignment_name varchar(255) null,
assignment_type varchar(255) null,
source_input_keys varchar(255) null,
target_output_key varchar(255) null,
assigned_runnable_name varchar(255) null,
assigned_runnable_type varchar(255) null,
assignment_expression varchar(255) null,
assignment_input varchar(255) null,
assignment_output varchar(255) null,
existing_keys_preserved varchar(255) null,
overwrite_existing_key varchar(255) null,
parallel_assignment_enabled varchar(255) null,
assignment_priority bigint null,
assignment_start_time varchar(255) null,
constraint passthrough_chain_assignment_management_pk primary key(assignment_management_id));